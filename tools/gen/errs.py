#!/usr/bin/env python3
"""SB-006: generate internal/errs/codes.go from the registry table in manual/sb-errors.7.md.

Usage: python3 tools/gen/errs.py          # write the file
       python3 tools/gen/errs.py --check  # exit 1 if the file is out of date
The manual is the spec; this file is never edited by hand.
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC, OUT = ROOT / "manual/sb-errors.7.md", ROOT / "internal/errs/codes.go"

def rows():
    text = SRC.read_text(encoding="utf-8")
    table = text.split("## REGISTRY", 1)[1].split("\n## ", 1)[0]
    out = []
    for line in table.splitlines():
        m = re.match(r"^\| `(E[A-Z]+)` \| (\d{3}|—) \| (\d+) \| (.+?) \| (.+?) \|$", line)
        if m:
            code, http, exit_, meaning, remedy = m.groups()
            out.append((code, 0 if http == "—" else int(http), int(exit_), meaning, remedy))
    if not out:
        sys.exit("errs.py: no registry rows found in " + str(SRC))
    return out

def plain(s):
    return re.sub(r"[`*]", "", s).replace('"', '\\"')

def render(rs):
    lines = [
        "// Code generated by tools/gen/errs.py from manual/sb-errors.7.md. DO NOT EDIT.",
        "",
        "package errs",
        "",
        "// Registry codes, in manual order.",
        "const (",
    ]
    lines += [f'\t{c} Code = "{c}"' for c, *_ in rs]
    lines += [")", "", "var registry = map[Code]entry{"]
    for c, http, ex, meaning, remedy in rs:
        lines.append(f'\t{c}: {{http: {http}, exit: {ex}, meaning: "{plain(meaning)}", remedy: "{plain(remedy)}"}},')
    lines += ["}", ""]
    return subprocess.run(["gofmt"], input="\n".join(lines), capture_output=True, text=True, check=True).stdout

if __name__ == "__main__":
    want = render(rows())
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            sys.exit("errs.py: internal/errs/codes.go is out of date with manual/sb-errors.7.md; run python3 tools/gen/errs.py")
        print("errs.py: codes.go matches the manual")
    else:
        OUT.write_text(want, encoding="utf-8")
        print(f"errs.py: wrote {len(rows())} codes to {OUT.relative_to(ROOT)}")
